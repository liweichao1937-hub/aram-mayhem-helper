def alias_slug(q: str) -> str | None:
    q = (q or "").strip()
    if not q:
        return None
    if q in ALIASES:
        return ALIASES[q]
    low = q.lower()
    if low in ALIASES:
        return ALIASES[low]
    # 子串匹配：长词优先（避免「小」误伤）
    for k in sorted(ALIASES.keys(), key=len, reverse=True):
        if len(k) < 2:
            continue
        if k in q or k.lower() in low:
            return ALIASES[k]
    return None
